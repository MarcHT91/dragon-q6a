"""AWQ-style per-input-channel scaling (folded exactly into norms / producer rows) + GPTQ int4 for LFM3. CUDA.

usage: [CHAT=calib_chat.jsonl] python awq_gptq_lfm3.py MODEL_DIR WIKITEXT_PARQUET OUT_DIR AWQ_MODEL_DIR [n_seq=128] [seq_len=512]
Writes OUT_DIR/layer{i}.npz (same format as gptq_lfm3.py) and AWQ_MODEL_DIR: an fp32 model equivalent to MODEL_DIR
(scaled weights, per-layer safetensors + index), which the NPU builder must use together with OUT_DIR.
Folding: qkvg_in/inproj_in -> operator_norm gamma; gu_in -> ffn_norm gamma; o_in -> v_proj rows (shared per KV head);
out_in -> C rows of conv.in_proj; down_in -> w3 rows. Row scaling is invariant for per-output-channel quantization.
"""
import sys, time, math
from pathlib import Path
import numpy as np, torch
import pyarrow.parquet as pq
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "npu"))
from lfm3_ref import LFM3Ref
from tokenizers import Tokenizer

torch.set_grad_enabled(False)
DEV = "cuda" if torch.cuda.is_available() else "cpu"
M, WIKI, OUT, AWQ = sys.argv[1], sys.argv[2], Path(sys.argv[3]), Path(sys.argv[4]); OUT.mkdir(parents=True, exist_ok=True); AWQ.mkdir(parents=True, exist_ok=True)
NSEQ = int(sys.argv[5]) if len(sys.argv) > 5 else 128
SEQ = int(sys.argv[6]) if len(sys.argv) > 6 else 512
QMAX = 7
tok = Tokenizer.from_file(str(Path(M) / "tokenizer.json"))
BOS = tok.token_to_id("<|startoftext|>")

text = "\n".join(t for t in pq.read_table(WIKI)["text"].to_pylist() if t.strip())
ids = tok.encode(text, add_special_tokens=False).ids
rng = np.random.default_rng(0)
seqs = []
for _ in range(NSEQ):
    s = int(rng.integers(0, len(ids) - SEQ))
    seqs.append([BOS] + ids[s:s + SEQ - 1])
import os, json as _json
if os.environ.get("CHAT"):          # in-domain chat/tool/thinking sequences generated by gen_calib_lfm3.py
    chat = [_json.loads(l)["ids"][:SEQ] for l in open(os.environ["CHAT"])]
    seqs += chat
    print(f"+ {len(chat)} chat sequences ({sum(map(len, chat))} tok)")
print(f"{len(seqs)} seqs, {sum(map(len, seqs))} tok on {DEV}", flush=True)


def scales_mse(W):
    amax = W.abs().amax(1).clamp_min(1e-12)
    best_s, best_e = amax / QMAX, torch.full_like(amax, float("inf"))
    for r in torch.linspace(0.6, 1.0, 17):
        s = amax * r / QMAX
        e = ((torch.clamp(torch.round(W / s[:, None]), -QMAX - 1, QMAX) * s[:, None] - W) ** 2).sum(1)
        b = e < best_e
        best_e[b], best_s[b] = e[b], s[b]
    return best_s


def gptq(W, H, s, block=128, damp=0.01):
    W = W.clone(); n = W.shape[1]
    dead = torch.diag(H) == 0
    H = H.clone(); H[dead, dead] = 1; W[:, dead] = 0
    perm = torch.argsort(torch.diag(H), descending=True)
    W, H = W[:, perm], H[perm][:, perm]
    H += damp * torch.diag(H).mean() * torch.eye(n, device=H.device)
    Hinv = torch.linalg.cholesky(torch.cholesky_inverse(torch.linalg.cholesky(H)), upper=True)
    Q = torch.zeros_like(W)
    for i1 in range(0, n, block):
        i2 = min(i1 + block, n)
        W1, Hi = W[:, i1:i2].clone(), Hinv[i1:i2, i1:i2]
        Q1, E1 = torch.zeros_like(W1), torch.zeros_like(W1)
        for j in range(i2 - i1):
            w, d = W1[:, j], Hi[j, j]
            q = torch.clamp(torch.round(w / s), -QMAX - 1, QMAX)
            Q1[:, j] = q
            e = (w - q * s) / d
            W1[:, j:] -= e[:, None] * Hi[j, j:][None, :]
            E1[:, j] = e
        Q[:, i1:i2] = Q1
        W[:, i2:] -= E1 @ Hinv[i1:i2, i2:]
    return Q[:, torch.argsort(perm)]



import shutil, json
from safetensors.torch import save_file
ref = LFM3Ref(M, device=DEV)
H_, KV_, D_ = ref.H, ref.KV, ref.D; hid = ref.c["hidden_size"]
GROUPS = {
    "conv": {"inproj_in": ["conv.in_proj.weight"], "out_in": ["conv.out_proj.weight"]},
    "attn": {"qkvg_in": ["self_attn.q_proj.weight", "self_attn.k_proj.weight", "self_attn.v_proj.weight"],
             "o_in": ["self_attn.o_proj.weight"]},
    "mlp": {"gu_in": ["feed_forward.w1.weight", "feed_forward.w3.weight"], "down_in": ["feed_forward.w2.weight"]},
}
ROWS_PER_SEQ = 48


def rtn(W):
    s = scales_mse(W)
    return torch.clamp(torch.round(W / s[:, None]), -QMAX - 1, QMAX) * s[:, None]


def search(Xs, amean, Ws, shape_fn):
    """best per-input-channel scale s (W -> W*s, x -> x/s) by grid over alpha on the int4 RTN output error."""
    ref_out = [Xs @ W.T for W in Ws]
    den = sum(float((o ** 2).sum()) for o in ref_out)
    best = (float("inf"), None, None)
    for alpha in [i / 20 for i in range(21)]:
        s = shape_fn(amean.clamp_min(1e-5).pow(alpha))
        s = s / (s.max() * s.min()).sqrt()
        err = sum(float((((Xs / s) @ rtn(W * s[None]).T - o) ** 2).sum()) for W, o in zip(Ws, ref_out))
        if err < best[0]:
            best = (err, alpha, s)
    e0 = sum(float(((Xs @ rtn(W).T - o) ** 2).sum()) for W, o in zip(Ws, ref_out))
    return best[2], best[1], (e0 / den) ** 0.5, (best[0] / den) ** 0.5


def kv_shared(a):          # o_in channel (h, d): heads sharing a KV head must share the scale (folded into v rows)
    return a.view(KV_, H_ // KV_, D_).mean(1, keepdim=True).expand(KV_, H_ // KV_, D_).reshape(-1)


X = [ref.embed[torch.tensor(sq, device=DEV)] for sq in seqs]
NTOK = sum(len(sq) for sq in seqs)
gen = torch.Generator(device="cpu").manual_seed(0)
t0 = time.time()
wmap = {}
for i in range(int(os.environ.get("MAXL", ref.L))):
    w = {k: v.to(DEV) for k, v in ref.W.layer(i).items()}
    conv = ref.types[i] == "conv"
    groups = {**GROUPS["conv" if conv else "attn"], **GROUPS["mlp"]}
    # ---- AWQ: capture inputs (sampled rows + per-channel mean |x|) ----
    samp, amean = {}, {}
    for x in X:
        cap = {}
        ref.layer_forward(i, x, list(range(len(x))), None, w=w, cap=cap)
        idx = torch.randperm(len(x), generator=gen)[:ROWS_PER_SEQ].to(DEV)
        for k, a in cap.items():
            if k in groups:
                samp.setdefault(k, []).append(a[idx]); amean[k] = amean.get(k, 0) + a.abs().sum(0)
    info = []
    for k, names in groups.items():
        Xs = torch.cat(samp[k]); am = amean[k] / NTOK
        s, alpha, e0, e1 = search(Xs, am, [w[n] for n in names], kv_shared if k == "o_in" else (lambda t: t))
        info.append(f"{k} a={alpha:.2f} {e0:.3f}->{e1:.3f}")
        cols = names + (["self_attn.gate_proj.weight"] if k == "qkvg_in" else [])
        for n in cols:
            w[n] = w[n] * s[None]
        if k in ("qkvg_in", "inproj_in"):
            w["operator_norm.weight"] = w["operator_norm.weight"] / s
        elif k == "gu_in":
            w["ffn_norm.weight"] = w["ffn_norm.weight"] / s
        elif k == "o_in":
            sv = s.view(KV_, H_ // KV_, D_)[:, 0].reshape(-1)
            w["self_attn.v_proj.weight"] = w["self_attn.v_proj.weight"] / sv[:, None]
        elif k == "out_in":
            W = w["conv.in_proj.weight"].clone(); W[hid:2 * hid] /= s[:, None]; w["conv.in_proj.weight"] = W
        elif k == "down_in":
            w["feed_forward.w3.weight"] = w["feed_forward.w3.weight"] / s[:, None]
    del samp
    # ---- GPTQ on the scaled weights ----
    Hs = {}
    for x in X:
        cap = {}
        ref.layer_forward(i, x, list(range(len(x))), None, w=w, cap=cap)
        for k, a in cap.items():
            if k in groups:
                Hs[k] = Hs.get(k, 0) + a.T @ a
    out, wq, errs = {}, dict(w), []
    for k, names in groups.items():
        H = Hs[k] * (2.0 / NTOK)
        for nm in names:
            W = w[nm]
            s = scales_mse(W)
            Q = gptq(W, H, s)
            Wd = Q * s[:, None]
            tr = lambda d: float(torch.einsum("oi,ij,oj->", d, H, d))
            errs.append(f"{nm.split('.')[-2]} {math.sqrt(tr(Wd-W)/tr(W)):.3f}")
            out[nm + "_q"] = Q.T.contiguous().cpu().numpy().astype(np.int8)
            out[nm + "_s"] = s.cpu().numpy().astype(np.float32)
            wq[nm] = Wd
    del Hs
    np.savez(OUT / f"layer{i}.npz", **out)
    fn = f"awq_layer{i}.safetensors"
    save_file({f"model.layers.{i}.{k}": v.float().contiguous().cpu() for k, v in w.items()}, str(AWQ / fn))
    wmap.update({f"model.layers.{i}.{k}": fn for k in w})
    X = [ref.layer_forward(i, x, list(range(len(x))), None, w=wq)[0] for x in X]
    print(f"layer {i:2d} {ref.types[i][:5]:5} {time.time()-t0:6.0f}s  AWQ " + " | ".join(info) + "  GPTQ " + " ".join(errs), flush=True)
rest = {n: ref.W.get(n).cpu().contiguous() for n in ref.W.where if not n.startswith("model.layers.")}
save_file(rest, str(AWQ / "awq_rest.safetensors")); wmap.update({n: "awq_rest.safetensors" for n in rest})
json.dump({"weight_map": wmap}, open(AWQ / "model.safetensors.index.json", "w"))
for f in Path(M).iterdir():
    if f.suffix in (".json", ".jinja") and not f.name.startswith("model."):
        shutil.copy(f, AWQ / f.name)
print("done")
