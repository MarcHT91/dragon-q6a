"""GPTQ (symmetric int4, per-output-channel, act-order) for LFM3. Runs on CUDA if available.

usage: python gptq_lfm3.py MODEL_DIR WIKITEXT_PARQUET OUT_DIR [n_seq=128] [seq_len=512]
Writes OUT_DIR/layer{i}.npz with "<name>_q" int8 [in,out] (values -8..7) and "<name>_s" fp32 [out].
"""
import sys, time, math
from pathlib import Path
import numpy as np, torch
import pyarrow.parquet as pq
sys.path.insert(0, str(Path(__file__).resolve().parent))
from lfm3_ref import LFM3Ref
from tokenizers import Tokenizer

torch.set_grad_enabled(False)
DEV = "cuda" if torch.cuda.is_available() else "cpu"
M, WIKI, OUT = sys.argv[1], sys.argv[2], Path(sys.argv[3]); OUT.mkdir(parents=True, exist_ok=True)
NSEQ = int(sys.argv[4]) if len(sys.argv) > 4 else 128
SEQ = int(sys.argv[5]) if len(sys.argv) > 5 else 512
QMAX = 7
tok = Tokenizer.from_file(str(Path(M) / "tokenizer.json"))
BOS = tok.token_to_id("<|startoftext|>")

text = "\n".join(t for t in pq.read_table(WIKI)["text"].to_pylist() if t.strip())
ids = tok.encode(text, add_special_tokens=False).ids
rng = np.random.default_rng(0)
seqs = []
for _ in range(NSEQ):
    s = int(rng.integers(0, len(ids) - SEQ))
    seqs.append([BOS] + ids[s:s + SEQ - 1])
import os, json as _json
if os.environ.get("CHAT"):          # in-domain chat/tool/thinking sequences generated by gen_calib_lfm3.py
    chat = [_json.loads(l)["ids"][:SEQ] for l in open(os.environ["CHAT"])]
    seqs += chat
    print(f"+ {len(chat)} chat sequences ({sum(map(len, chat))} tok)")
print(f"{len(seqs)} seqs, {sum(map(len, seqs))} tok on {DEV}", flush=True)


def scales_mse(W):
    amax = W.abs().amax(1).clamp_min(1e-12)
    best_s, best_e = amax / QMAX, torch.full_like(amax, float("inf"))
    for r in torch.linspace(0.6, 1.0, 17):
        s = amax * r / QMAX
        e = ((torch.clamp(torch.round(W / s[:, None]), -QMAX - 1, QMAX) * s[:, None] - W) ** 2).sum(1)
        b = e < best_e
        best_e[b], best_s[b] = e[b], s[b]
    return best_s


def gptq(W, H, s, block=128, damp=0.01):
    W = W.clone(); n = W.shape[1]
    dead = torch.diag(H) == 0
    H = H.clone(); H[dead, dead] = 1; W[:, dead] = 0
    perm = torch.argsort(torch.diag(H), descending=True)
    W, H = W[:, perm], H[perm][:, perm]
    H += damp * torch.diag(H).mean() * torch.eye(n, device=H.device)
    Hinv = torch.linalg.cholesky(torch.cholesky_inverse(torch.linalg.cholesky(H)), upper=True)
    Q = torch.zeros_like(W)
    for i1 in range(0, n, block):
        i2 = min(i1 + block, n)
        W1, Hi = W[:, i1:i2].clone(), Hinv[i1:i2, i1:i2]
        Q1, E1 = torch.zeros_like(W1), torch.zeros_like(W1)
        for j in range(i2 - i1):
            w, d = W1[:, j], Hi[j, j]
            q = torch.clamp(torch.round(w / s), -QMAX - 1, QMAX)
            Q1[:, j] = q
            e = (w - q * s) / d
            W1[:, j:] -= e[:, None] * Hi[j, j:][None, :]
            E1[:, j] = e
        Q[:, i1:i2] = Q1
        W[:, i2:] -= E1 @ Hinv[i1:i2, i2:]
    return Q[:, torch.argsort(perm)]


ref = LFM3Ref(M, device=DEV)
GROUPS = {
    "conv": {"inproj_in": ["conv.in_proj.weight"], "out_in": ["conv.out_proj.weight"]},
    "attn": {"qkvg_in": ["self_attn.q_proj.weight", "self_attn.k_proj.weight", "self_attn.v_proj.weight"],
             "o_in": ["self_attn.o_proj.weight"]},
    "mlp": {"gu_in": ["feed_forward.w1.weight", "feed_forward.w3.weight"], "down_in": ["feed_forward.w2.weight"]},
}
X = [ref.embed[torch.tensor(sq, device=DEV)] for sq in seqs]
NTOK = sum(len(sq) for sq in seqs)
t0 = time.time()
import os
for i in range(int(os.environ.get("MAXL", ref.L))):
    w = {k: v.to(DEV) for k, v in ref.W.layer(i).items()}
    groups = {**GROUPS["conv" if ref.types[i] == "conv" else "attn"], **GROUPS["mlp"]}
    Hs = {}
    for x in X:
        cap = {}
        ref.layer_forward(i, x, list(range(len(x))), None, w=w, cap=cap)
        for k, a in cap.items():
            if k in groups:
                Hs[k] = Hs.get(k, 0) + a.T @ a
    out, wq, errs = {}, dict(w), []
    for k, names in groups.items():
        H = Hs[k] * (2.0 / NTOK)
        for nm in names:
            W = w[nm]
            s = scales_mse(W)
            Q = gptq(W, H, s)
            Wd = Q * s[:, None]
            tr = lambda d: float(torch.einsum("oi,ij,oj->", d, H, d))
            rtn = torch.clamp(torch.round(W / s[:, None]), -QMAX - 1, QMAX) * s[:, None] - W
            errs.append(f"{nm.split('.')[-2]} {math.sqrt(tr(rtn)/tr(W)):.3f}->{math.sqrt(tr(Wd-W)/tr(W)):.3f}")
            out[nm + "_q"] = Q.T.contiguous().cpu().numpy().astype(np.int8)
            out[nm + "_s"] = s.cpu().numpy().astype(np.float32)
            wq[nm] = Wd
    np.savez(OUT / f"layer{i}.npz", **out)
    X = [ref.layer_forward(i, x, list(range(len(x))), None, w=wq)[0] for x in X]
    print(f"layer {i:2d} {ref.types[i][:5]:5} {time.time()-t0:6.0f}s  RTN->GPTQ: " + " | ".join(errs), flush=True)
print("done")
